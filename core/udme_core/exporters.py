"""JSON / CSV / Markdown(+Mermaid ERD) / SQL DDL exports (plan 13)."""
from __future__ import annotations
import csv, io, json
from .model import Package, RelationshipCandidate, BusinessClassification


def to_json(pkg, rels, maps) -> str:
    return json.dumps({"package": pkg.model_dump(mode="json"),
                       "relationships": [r.model_dump() for r in rels],
                       "business_mappings": [m.model_dump() for m in maps]}, indent=2, ensure_ascii=False)


def relationships_csv(rels: list[RelationshipCandidate]) -> str:
    b = io.StringIO(); w = csv.writer(b)
    w.writerow(["source", "source_cols", "target", "target_cols", "type", "score", "declared", "status", "evidence"])
    for r in rels:
        w.writerow([r.source_table, ",".join(r.source_columns), r.target_table, ",".join(r.target_columns),
                    r.candidate_type, r.score, r.declared, r.status, ";".join(r.evidence)])
    return b.getvalue()


def _mm(s: str) -> str:
    return "".join(ch if ch.isalnum() else "_" for ch in s)


def to_markdown(pkg: Package, rels, maps) -> str:
    mp = {m.object_id: m for m in maps}
    L = [f"# Data dictionary — {pkg.source.engine} {pkg.source.engine_version or ''}".strip(),
         f"\nConnector: `{pkg.source.connector}` · metadata-only: **{pkg.source.metadata_only}**"]
    if pkg.source.warnings: L += ["\n> Warnings: " + "; ".join(pkg.source.warnings)]
    L += ["\n## Relationship map (Mermaid)\n", "```mermaid", "erDiagram"]
    for r in rels:
        L.append(f'  {_mm(r.target_table)} ||--{"o|" if r.candidate_type == "one_to_one" else "o{"} {_mm(r.source_table)} : "{r.score:.2f}{"" if r.declared else "?"}"')
    L += ["```", "\n## Tables"]
    for s, t in pkg.iter_tables():
        oid = f"{s}.{t.name}"; m = mp.get(oid)
        L.append(f"\n### {oid} ({t.object_type})")
        if m: L.append(f"*Proposed:* `{m.label}` — confidence {m.confidence} — " + ("**review required**" if m.review_required else "approved by reviewer"))
        L += ["", "| # | Column | Type | Normalized | Null | PK |", "|--|--|--|--|--|--|"]
        for c in t.columns:
            L.append(f"| {c.ordinal} | {c.name} | {c.native_type} | {c.normalized_type} | "
                     f"{'?' if c.nullable is None else c.nullable} | {'✔' if c.name in t.primary_key else ''} |")
    L += ["\n## Relationships", "", "| Source | Target | Type | Score | Status | Evidence |", "|--|--|--|--|--|--|"]
    for r in rels:
        L.append(f"| {r.source_table}.{','.join(r.source_columns)} | {r.target_table}.{','.join(r.target_columns)} | "
                 f"{r.candidate_type} | {r.score} | {r.status} | {', '.join(r.evidence)} |")
    return "\n".join(L) + "\n"


def to_ddl(pkg: Package) -> str:
    """Documentation DDL only (native types preserved). Never executed by UDME."""
    out = ["-- Generated by UDME from metadata. Reference only; not executed against any source."]
    for s, t in pkg.iter_tables():
        if t.object_type != "table": continue
        lines = [f'  "{c.name}" {c.native_type}{"" if c.nullable in (None, True) else " NOT NULL"}' for c in t.columns]
        if t.primary_key: lines.append("  PRIMARY KEY (" + ", ".join(f'"{c}"' for c in t.primary_key) + ")")
        for fk in t.foreign_keys:
            lines.append("  FOREIGN KEY (" + ", ".join(f'"{c}"' for c in fk.columns) + f') REFERENCES "{fk.ref_table}" (' +
                         ", ".join(f'"{c}"' for c in fk.ref_columns) + ")")
        out.append(f'CREATE TABLE "{s}"."{t.name}" (\n' + ",\n".join(lines) + "\n);")
    return "\n\n".join(out) + "\n"
