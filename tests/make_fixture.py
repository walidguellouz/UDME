"""Synthetic legacy DB: no declared FKs, French abbreviations (plan 16.1). Fictional names."""
import sqlite3, sys
def build(path):
    c = sqlite3.connect(path)
    c.executescript("""
    CREATE TABLE T_ART (ID_ART INTEGER PRIMARY KEY, CODE_EAN TEXT, DESIGNATION TEXT, PRIX_VENTE NUMERIC, TVA NUMERIC);
    CREATE TABLE T_FOUR (ID_FOUR INTEGER PRIMARY KEY, NOM TEXT, ADRESSE TEXT, TEL TEXT);
    CREATE TABLE T_STOCK (ID_STOCK INTEGER PRIMARY KEY, ID_ART INTEGER, QTE NUMERIC, DEPOT TEXT);
    CREATE TABLE T_VTE (ID_VTE INTEGER PRIMARY KEY, DATE_VTE DATE, TOTAL_TTC NUMERIC);
    CREATE TABLE T_LIGVTE (ID_LIG INTEGER PRIMARY KEY, ID_VTE INTEGER, ID_ART INTEGER, QTE NUMERIC, PRIX NUMERIC);
    CREATE TABLE T_ACHAT (ID_ACHAT INTEGER PRIMARY KEY, ID_FOUR INTEGER, DATE_ACHAT DATE);
    CREATE TABLE ZZ_MISC (A TEXT, B TEXT);
    CREATE TABLE ORDERS (id INTEGER PRIMARY KEY, customer_id INTEGER, FOREIGN KEY(customer_id) REFERENCES CUSTOMERS(id));
    CREATE TABLE CUSTOMERS (id INTEGER PRIMARY KEY, name TEXT);
    """); c.commit(); c.close()
if __name__ == "__main__": build(sys.argv[1])
